#!/usr/bin/env node
/**
 * NEW-ARCHITECTURE COMPLETION MATRIX: validator and score calculator.
 *
 * Reads docs/architecture/completion-matrix/work-packages.json and computes, per work package:
 *   score = 0.10*spec + 0.35*(impl*100) + 0.25*(impl*integration) + 0.20*(impl*verification) + 0.10*(impl*operational)
 * (every input on a 0-100 scale; impl is 0-1). Aggregation is weighted by `units` (requirement units).
 *
 *   node scripts/completion-matrix.mjs            validate + print the results
 *   node scripts/completion-matrix.mjs --json     print results as JSON
 *   node scripts/completion-matrix.mjs --check    exit 1 if the data file is invalid (CI-safe)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const DATA = resolve(here, '../../docs/architecture/completion-matrix/work-packages.json');
const data = JSON.parse(readFileSync(DATA, 'utf8'));
const W = data.dimensions;

const errors = [];
const pct = (v) => typeof v === 'number' && v >= 0 && v <= 100;
const sumW = Object.values(W).reduce((a, b) => a + b, 0);
if (Math.abs(sumW - 1) > 1e-9) errors.push(`dimension weights sum to ${sumW}, expected 1`);

const ids = new Set();
function check(row, kind) {
  if (!row.id) errors.push(`${kind}: missing id`);
  if (ids.has(row.id)) errors.push(`duplicate id ${row.id}`);
  ids.add(row.id);
  if (typeof row.impl !== 'number' || row.impl < 0 || row.impl > 1) errors.push(`${row.id}: impl must be 0..1`);
  for (const k of ['spec', 'integration', 'verification', 'operational']) if (!pct(row[k])) errors.push(`${row.id}: ${k} must be 0..100`);
  if (!row.evidence || row.evidence.length < 4) errors.push(`${row.id}: evidence is required`);
}

export function score(r) {
  return W.spec * r.spec + W.functional * r.impl * 100 + W.integration * r.impl * r.integration
    + W.verification * r.impl * r.verification + W.operational * r.impl * r.operational;
}

for (const wp of data.workPackages) { check(wp, 'workPackage'); if (!(wp.units > 0)) errors.push(`${wp.id}: units must be > 0`); }
for (const g of data.guardrailSlice) { check(g, 'guardrail'); g.units = 1; }

function aggregate(rows, key) {
  const groups = new Map();
  for (const r of rows) {
    const k = key ? r[key] : 'ALL';
    const g = groups.get(k) ?? { units: 0, weighted: 0, count: 0 };
    g.units += r.units; g.weighted += r.units * score(r); g.count += 1;
    groups.set(k, g);
  }
  return Object.fromEntries([...groups].map(([k, g]) => [k, { packages: g.count, units: g.units, score: +(g.weighted / g.units).toFixed(2) }]));
}

const out = {
  asOf: data.asOf, mainCommit: data.mainCommit,
  fullScope: aggregate(data.workPackages).ALL,
  byFamily: aggregate(data.workPackages, 'family'),
  byLayer: aggregate(data.workPackages.filter((w) => w.layer), 'layer'),
  byDomain: aggregate(data.workPackages, 'domain'),
  guardrailSlice: aggregate(data.guardrailSlice).ALL,
  perPackage: data.workPackages.map((w) => ({ id: w.id, title: w.title, units: w.units, score: +score(w).toFixed(1) })),
  perGuardrail: data.guardrailSlice.map((g) => ({ id: g.id, title: g.title, score: +score(g).toFixed(1) })),
};

if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
if (process.argv.includes('--check')) { console.log(`completion matrix valid: ${data.workPackages.length} work packages, ${data.guardrailSlice.length} guardrail criteria`); process.exit(0); }

if (process.argv.includes('--write-doc')) {
  const L = [];
  const f1 = (n) => n.toFixed(1);
  L.push('# NEW-ARCHITECTURE COMPLETION MATRIX', '');
  L.push(`Workstream NEW-ARCHITECTURE-01. Generated by \`infinicus-platform/scripts/completion-matrix.mjs --write-doc\` from \`docs/architecture/completion-matrix/work-packages.json\`; do not edit by hand. As of ${out.asOf} on main \`${out.mainCommit}\`. Scope: Stack B only; Stack A is frozen and not scored.`, '');
  L.push('## 1. Headline', '', '| Basis | Score | Definition |', '|---|---|---|');
  L.push(`| **Full scope (authoritative 90% target, owner ruling 2026-10-22)** | **${f1(out.fullScope.score)}%** | every requirement unit of the 8 domains / 9 layers (${out.fullScope.units} units, ${out.fullScope.packages} work packages) |`);
  L.push(`| Guardrail slice (reported, not the target) | ${f1(out.guardrailSlice.score)}% | the 13 acceptance criteria (G-A..G-M) of the first governed action |`, '');
  L.push('## 2. Method', '', 'Weights: specification 10%, functional 35%, end-to-end integration 25%, automated verification 20%, operational readiness 10%.', '');
  L.push('`score = 0.10*spec + 0.35*(impl*100) + 0.25*(impl*integration) + 0.20*(impl*verification) + 0.10*(impl*operational)` (inputs 0-100, impl 0-1). Integration, verification and operational credit scale with implementation, so unbuilt work cannot earn them. Aggregation is weighted by requirement units. Every row carries an evidence string. A score changes only with a linked rubric criterion and merged evidence (see History). Rubric:', '');
  for (const [k, v] of Object.entries(data.levels)) L.push(`- **${k}**: ${v}`);
  L.push('', '## 3. Results by layer', '', '| Layer | Units | Score |', '|---|---|---|');
  for (const [k, v] of Object.entries(out.byLayer)) L.push(`| ${k} | ${v.units} | ${f1(v.score)}% |`);
  L.push('', '## 4. Results by domain', '', '| Domain | Units | Score |', '|---|---|---|');
  for (const [k, v] of Object.entries(out.byDomain)) L.push(`| ${k} | ${v.units} | ${f1(v.score)}% |`);
  L.push('', '## 5. Work packages', '', '| ID | Title | Units | Score |', '|---|---|---|---|');
  for (const p of out.perPackage) L.push(`| ${p.id} | ${p.title} | ${p.units} | ${f1(p.score)}% |`);
  L.push('', '## 6. Guardrail slice criteria', '', '| ID | Criterion | Score |', '|---|---|---|');
  for (const p of out.perGuardrail) L.push(`| ${p.id} | ${p.title} | ${f1(p.score)}% |`);
  L.push('', '## 7. Checkpoints', '', '| Checkpoint | Full scope | Slice | Status |', '|---|---|---|---|');
  const reached = (t) => (out.fullScope.score >= t ? 'reached' : 'pending');
  L.push(`| Baseline (5fc8489) | 29.1% | 78.9% | recorded |`, `| Current (${out.mainCommit}) | ${f1(out.fullScope.score)}% | ${f1(out.guardrailSlice.score)}% | - |`);
  for (const c of [75, 80, 85, 90]) L.push(`| ${c}% | - | - | ${reached(c)} |`);
  L.push('', '## 8. History (every score change, with its criterion)', '');
  for (const h of data.history ?? []) {
    L.push(`### ${h.date} main \`${h.mainCommit}\` - ${h.label}`);
    if (h.fullScope !== undefined) L.push(`Full scope ${h.fullScope}%, guardrail slice ${h.guardrailSlice}%.`);
    for (const c of h.changes) L.push(`- **${c.workPackage}** ${c.field}: ${c.from} -> ${c.to}. Criterion: ${c.criterion}. Evidence: ${c.evidence}`);
    for (const n of h.notScored ?? []) L.push(`- Not scored: ${n}`);
    L.push('');
  }
  L.push('## 9. Rules for updating', '', '- Raise a score only with evidence merged on main (code, test, CI result). Unmerged branches do not count.', '- Closing an architecture finding is not itself a score change; link the specific rubric criterion.', '- Owner-decision and hardware items stay at their current score and are marked BLOCKED, never estimated.', '- Run `node scripts/completion-matrix.mjs --check` before committing, and `--write-doc` to regenerate the document.', '- Weights, rubric and units change only by owner decision; record the change in History.', '');
  writeFileSync(resolve(here, '../../docs/architecture/NEW_ARCHITECTURE_COMPLETION_MATRIX.md'), L.join('\n'));
  console.log('wrote NEW_ARCHITECTURE_COMPLETION_MATRIX.md');
  process.exit(0);
}
if (process.argv.includes('--json')) { console.log(JSON.stringify(out, null, 2)); process.exit(0); }
console.log(`Completion matrix as of ${out.asOf} (main ${out.mainCommit})`);
console.log(`Full scope:      ${out.fullScope.score}%  (${out.fullScope.packages} packages, ${out.fullScope.units} units)`);
console.log(`Guardrail slice: ${out.guardrailSlice.score}%  (${out.guardrailSlice.packages} criteria)`);
for (const [t, v] of [['family', out.byFamily], ['layer', out.byLayer], ['domain', out.byDomain]]) {
  console.log(`\nBy ${t}:`); for (const [k, g] of Object.entries(v)) console.log(`  ${k.padEnd(14)} ${String(g.score).padStart(5)}%  (${g.units} units)`);
}
